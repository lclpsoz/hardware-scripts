#!/bin/bash
# sync-from-pi.sh - copy what runs on the Pi into raspberry-pi/pi/ (secrets redacted).
#
# Run from the repo root:   bash raspberry-pi/scripts/sync-from-pi.sh
# Then review with:         git diff raspberry-pi/pi
#
# Read-only on the Pi. Needs the `pi` SSH alias and the docker group (no sudo).
# The repo is public, so every pulled file goes through redact() and the script
# refuses to finish if anything secret-looking survives. proxy/ and netq/ are
# authored in the repo and deployed to the Pi, so for those it only reports drift.
set -euo pipefail
cd "$(dirname "$0")/../pi"

redact() {
  # Values of password/token/key-like settings become "<redacted>", except plain
  # true/false flags (for example SETPWD_enable_password=False), which are safe.
  sed -E \
    -e '/^[^=:]*[:=][[:space:]]*"?(true|false)"?[[:space:]]*$/I!s/^([[:space:]]*-?[[:space:]]*"?[A-Za-z0-9_.]*(PASSWORD|PASSWD|PASS|TOKEN|SECRET|PWHASH|TOTP|EMAIL|KEY)[A-Za-z0-9_.]*"?[[:space:]]*[:=][[:space:]]*).+$/\1"<redacted>"/I' \
    -e 's/PARTUUID=[0-9a-fA-F-]+/PARTUUID=<redacted>/g' \
    -e 's/ds=nocloud;i=[^ ]+/ds=nocloud;i=<redacted>/g' \
    -e 's/\b([0-9a-fA-F]{2}:){5}[0-9a-fA-F]{2}\b/xx:xx:xx:xx:xx:xx/g'
}

pull() {   # pull <remote command> <local file>
  mkdir -p "$(dirname "$2")"
  if ssh pi "$1" 2>/dev/null | redact > "$2.tmp"; then
    mv "$2.tmp" "$2"; echo "  $2"
  else
    rm -f "$2.tmp" "$2"; echo "  missing on the Pi: $2"
  fi
}

echo "== containers"
pull 'cat ~/pihole/docker-compose.yml' pihole/docker-compose.yml
pull 'cat ~/netalertx/docker-compose.yml' netalertx/docker-compose.yml
pull 'cat ~/beszel/docker-compose.yml' beszel/docker-compose.yml

echo "== Pi-hole settings that differ from the defaults"
# Find the changed keys (arrays carry the marker on their closing line), then
# read each value back with pihole-FTL --config. Secret keys are never read.
ssh pi 'docker exec -i pihole sh -s' > pihole/pihole-changed.toml.tmp <<'EOF'
echo "# Pi-hole v6 settings that differ from the defaults (generated by sync-from-pi.sh)"
awk '
  /^[ \t]*\[[^]]*\][ \t]*$/ { s = $0; gsub(/^[ \t]*\[|\][ \t]*$/, "", s); next }
  /^[ \t]*[A-Za-z0-9_]+[ \t]*=/ { k = $1 }
  /### CHANGED/ { src = ($0 ~ /CHANGED \(env\)/) ? "compose env" : "pihole.toml"; d = $0; sub(/.*default = /, "", d); print s "." k "\t" src "\t" d }
' /etc/pihole/pihole.toml | while IFS="$(printf '\t')" read -r key src def; do
  case "$key" in
    *pwhash*|*password*|*totp*|*secret*) val='"<redacted>"' ;;
    *) val=$(pihole-FTL --config "$key" | tr '\n' ' ' | sed 's/ *$//') ;;
  esac
  printf '%s = %s    # default %s (set in %s)\n' "$key" "$val" "$def" "$src"
done
EOF
redact < pihole/pihole-changed.toml.tmp > pihole/pihole-changed.toml && rm pihole/pihole-changed.toml.tmp
echo "  pihole/pihole-changed.toml"

echo "== NetAlertX settings (selected, secrets redacted)"
pull 'docker exec netalertx grep -E "^([A-Z0-9]+_(RUN|RUN_SCHD|RUN_TIMEOUT|CMD)|LOADED_PLUGINS|SCAN_SUBNETS|TIMEZONE|LOG_LEVEL|DAYS_TO_KEEP_EVENTS|HRS_TO_KEEP_[A-Z]+|PLUGINS_KEEP_HIST|REFRESH_FQDN|SETPWD_enable_password|UI_LANG|API_TOKEN)=" /data/config/app.conf' netalertx/app-settings.conf

echo "== host: systemd units, scripts, boot config"
for f in /etc/systemd/system/cpupower-powersave.service /etc/systemd/system/uv-snapshot.service \
         /etc/systemd/system/uv-web.service /etc/systemd/system/dpkg-db-backup.service.d/limit.conf \
         /etc/systemd/journald.conf.d/size.conf /etc/logrotate.d/uv-events \
         /usr/local/bin/uv-snapshot.sh /usr/local/bin/uv-web.py \
         /boot/firmware/config.txt /boot/firmware/cmdline.txt; do
  pull "cat $f" "system$f"
done

echo "== snapshot of what is running"
ssh pi 'echo "# Generated by sync-from-pi.sh on $(date -Is)"; echo; echo "kernel: $(uname -r)"; echo "os: $(. /etc/os-release; echo $PRETTY_NAME)"; echo; docker ps --format "{{.Names}}\t{{.Image}}\t{{.Status}}" | sort; echo; docker images --format "{{.Repository}}:{{.Tag}}\t{{.ID}}\t{{.CreatedSince}}" | sort; echo; systemctl is-enabled cpupower-powersave.service uv-snapshot.service uv-web.service 2>&1 | paste -sd" "' | redact > running.txt
echo "  running.txt"

echo "== drift check for repo-authored files (repo -> Pi)"
for f in proxy/docker-compose.yml proxy/nginx.conf proxy/www/index.html netq/docker-compose.yml netq/netq.py netalertx/lang.php.patched; do
  remote="~/${f}"
  if ssh pi "cat $remote" 2>/dev/null | cmp -s - "$f"; then echo "  same: $f"; else echo "  DIFFERS: $f (deploy with: scp raspberry-pi/pi/$f pi:$f)"; fi
done

echo "== secret guard"
if grep -rIn -E 'ssh-(ed25519|rsa) [A-Za-z0-9+/]{20}|BEGIN [A-Z ]*PRIVATE|\$BALLOON|\$argon|[0-9a-f]{40,}' . \
   --exclude=netq.py --exclude='lang.php*' --exclude='*.patch'; then
  echo "Secret-looking text found above: fix redact() before committing." >&2
  exit 1
fi
echo "  nothing secret-looking found"
